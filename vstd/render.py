"""Render the managed block for AGENTS.md and the CLAUDE.md wrapper.

Output is deterministic: the same rules and config always give the same bytes
(UTF-8, LF line endings, no timestamps).
"""

from __future__ import annotations

from vstd.config import Config
from vstd.markers import BEGIN_PREFIX, END_LINE, body_hash
from vstd.rules import Profile, RuleSet

CLAUDE_IMPORT = "@AGENTS.md"

PRECEDENCE = (
    "Precedence: MUST rules apply everywhere and cannot be overridden in this repository. "
    "SHOULD rules apply unless listed under \"Project overrides\" below. "
    "Project instructions after this block add detail but never weaken a MUST rule."
)

PROJECT_SECTION = (
    "\n"
    "# Project instructions\n"
    "\n"
    "Owned by this repository; sync never rewrites anything outside the venuvra-standards block.\n"
    "Add build and test commands, architecture notes and project rules here.\n"
)

CLAUDE_MD = (
    f"{CLAUDE_IMPORT}\n"
    "\n"
    "<!-- Claude Code-specific notes go below. Shared and project rules live in AGENTS.md. -->\n"
)


def _profile_lines(profile: Profile) -> list[str]:
    lines = [f"## {profile.title}", ""]
    lines += [f"- [{r.id} {r.level}] {r.text}" for r in profile.rules]
    lines.append("")
    return lines


def _sentence(text: str) -> str:
    text = text.rstrip()
    return text if text.endswith((".", "!", "?")) else text + "."


def _override_line(o) -> str:
    where = f" in `{o.scope}`" if o.scope else ""
    expiry = f", expires {o.expires.isoformat()}" if o.expires else ""
    return (
        f"- {o.rule} (SHOULD){where}: {_sentence(o.replacement)} "
        f"Reason: {_sentence(o.reason)} Approved by @{o.approved_by} on {o.approved_on.isoformat()}{expiry}."
    )


def render_body(ruleset: RuleSet, config: Config) -> str:
    stacks = sorted(config.stacks)
    lines = [
        f"# Venuvra engineering standards v{config.version}",
        "",
        f"Stacks: {', '.join(stacks) if stacks else 'none (core rules only)'}",
        "",
        PRECEDENCE,
        "",
    ]
    for profile in ruleset.core_profiles():
        lines += _profile_lines(profile)
    for stack in stacks:
        lines += _profile_lines(ruleset.stack_profile(stack))
    lines += ["## Project overrides", ""]
    if config.overrides:
        ordered = sorted(config.overrides, key=lambda o: (o.rule, o.scope or ""))
        lines += [_override_line(o) for o in ordered]
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def render_block(ruleset: RuleSet, config: Config) -> str:
    body = render_body(ruleset, config)
    begin = (
        f"{BEGIN_PREFIX}v{config.version} sha256={body_hash(body)} "
        "Generated by vstd. Change .venuvra/standards.toml, not this block. -->"
    )
    return f"{begin}\n{body}{END_LINE}\n"


def render_new_agents_md(ruleset: RuleSet, config: Config) -> str:
    """AGENTS.md for a repo that doesn't have one yet."""
    return render_block(ruleset, config) + PROJECT_SECTION
